const DIA_MS = 86_400_000;

/**
 * Fecha ISO (yyyy-mm-dd) desplazada respecto de hoy. Se usa para anclar los eventos
 * mock cerca del "presente" de la demo, así las misiones por evento siempre se pueden
 * demostrar sin importar el día en que se abra la app.
 */
const fechaRelativa = (diasDesdeHoy: number): string =>
  new Date(Date.now() + diasDesdeHoy * DIA_MS).toISOString().slice(0, 10);

/**
 * Marketplace de locales afiliados a Premia.ar.
 * Nombres 100% ficticios (no son marcas reales); la geografía sí es real:
 * todas las coordenadas caen dentro del barrio de Palermo, Buenos Aires.
 */
export interface Negocio {
  id: string;
  nombre: string;
  categoria: string;
  rubro: Rubro;
  /** Rubros ADICIONALES solo para que el negocio aparezca también en esos filtros/categorías
   *  (ej. un bar que también sirve café real). No cambia el tema visual de la tarjeta, que
   *  sigue siendo el de `rubro`. */
  rubrosSecundarios?: Rubro[];
  emoji: string;
  lat: number;
  lng: number;
  /** Clientes que ya usan el club en este local (números de local de barrio). */
  clientesActivos: number;
  /** Fecha ISO en la que el local se sumó a Premia.ar. */
  fechaAlta: string;
  recompensas: Recompensa[];
  /** Eventos con fecha cargados por el dueño (misiones por evento). */
  eventos?: EventoNegocio[];
  /** Franja horaria valle con puntos x2, informada al cliente como beneficio. */
  horarioValle?: HorarioValle;
  /**
   * Horario real de apertura del local (ficticio pero plausible — no hay dato real de
   * horarios de dueños todavía). Array porque un negocio puede tener franjas distintas
   * (ej. mediodía y noche); soporta cruzar medianoche (`hasta` < `desde`, ver lib/horarios.ts).
   * Sin este campo, la pantalla no muestra "Abierto"/"Cerrado" — nunca se inventa el dato.
   */
  horarioApertura?: HorarioValle[];
  /** Promos permanentes del local (2x1, delivery gratis, descuento, horario). */
  promos?: Promo[];
  /** Beneficios NO monetarios reservados al nivel más alto (VIP) de ESTE local. */
  beneficiosVip?: string[];
  /** Puntos desde los que un cliente es VIP en ESTE local. `null`/`undefined` = sin configurar (usa el umbral genérico de demo). */
  vipDesdePuntos?: number | null;
  /** Combo de asado de fin de semana destacado (carnicerías). */
  comboFinde?: ComboFinde;
  /** URL ya subida a otro lado (sin upload propio, mismo patrón que la carta digital). */
  logoUrl?: string;
  /** Imagen de portada/cabecera del negocio, mismo patrón sin upload. */
  portadaUrl?: string;
  /** Pool de premios de la ruleta semanal de ESTE local. Sin esto, se usa el pool genérico. */
  premiosRuleta?: PremioRuleta[];
  /**
   * Copy editorial corto para "Premia recomienda" (Home). BORRADOR pendiente de revisión de
   * Tobias — recién hay 4 cargados a modo de ejemplo, ninguno es texto de marketing final.
   * Sin este campo, el negocio no aparece en esa sección (no se fuerza contenido genérico).
   */
  historiaCorta?: string;
}

/** Relación de puntos del cliente con UN negocio (independiente por local). */
export interface RelacionNegocio {
  puntos: number;
  ultimaVisitaDias: number;
  historial: Visita[];
}

